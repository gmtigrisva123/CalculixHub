/**
 * Writes src/styles/fonts.css from the installed Fontsource packages.
 *
 * The fonts are served from this origin instead of Google's, so a first visit
 * makes no third-party connection before it can draw text. Each family keeps
 * its usual name ("Archivo", not Fontsource's "Archivo Variable"), which is
 * the name the design tokens ask for (tokens.css, --font-sans / --font-serif).
 *
 * Three families, and no more (design.md, "Typography"):
 *
 *   Archivo           the interface: one variable file per subset carrying both
 *                     the weight and the width axis.
 *   Old Standard TT   headings and anything set to be read: the Modern style of
 *                     early scientific printing, the lineage Computer Modern
 *                     comes from. Static cuts: 400, 400 italic, 700.
 *   CM Digits         not a new typeface: KaTeX's Computer Modern, restricted
 *                     by unicode-range to the ten digits and placed first in
 *                     both stacks, so every numeral in the interface is set in
 *                     the mathematics face without any markup.
 *
 * Only the Latin, Latin Extended and Vietnamese subsets are kept. Each is its
 * own file behind a `unicode-range`, so a page of plain English downloads the
 * Latin file alone.
 *
 * Run after changing a font package:  node scripts/generate-fonts-css.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const KEEP = ['latin', 'latin-ext', 'vietnamese'];
const SOURCES = [
  { scope: '@fontsource-variable', pkg: 'archivo', css: 'wdth.css', family: 'Archivo' },
  { scope: '@fontsource-variable', pkg: 'archivo', css: 'wdth-italic.css', family: 'Archivo' },
  { scope: '@fontsource', pkg: 'old-standard-tt', css: '400.css', family: 'Old Standard TT' },
  { scope: '@fontsource', pkg: 'old-standard-tt', css: '400-italic.css', family: 'Old Standard TT' },
  { scope: '@fontsource', pkg: 'old-standard-tt', css: '700.css', family: 'Old Standard TT' },
];

/** Computer Modern, digits only. The same files KaTeX already ships. */
const DIGITS = [
  { file: 'KaTeX_Main-Regular', style: 'normal', weight: '100 599' },
  { file: 'KaTeX_Main-Bold', style: 'normal', weight: '600 900' },
  { file: 'KaTeX_Main-Italic', style: 'italic', weight: '100 599' },
  { file: 'KaTeX_Main-BoldItalic', style: 'italic', weight: '600 900' },
];

let out = `/*
 * Self-hosted webfonts. GENERATED by scripts/generate-fonts-css.mjs: edit that
 * script, not this file.
 *
 * The faces the first screen is set in are also preloaded from index.html, so
 * they are usually in hand before the first frame is drawn.
 */\n`;

for (const { scope, pkg, css, family } of SOURCES) {
  const source = readFileSync(`node_modules/${scope}/${pkg}/${css}`, 'utf8');
  // Each block is headed by its file name, e.g. "archivo-latin-ext-wdth-normal".
  for (const match of source.matchAll(/\/\* ([a-z0-9-]+) \*\/\s*@font-face\s*\{([^}]*)\}/g)) {
    const [, file, body] = match;
    const subset = KEEP.find(name => file.startsWith(`${pkg}-${name}-`) && !(name === 'latin' && file.startsWith(`${pkg}-latin-ext-`)));
    if (!subset) continue;
    const rules = body
      .replace(/font-family:[^;]+;/, `font-family: '${family}';`)
      // Static packages list a .woff after the .woff2; every browser this app supports reads woff2.
      .replace(/,\s*url\([^)]*\.woff\)\s*format\('woff'\)/g, '')
      .replace(/url\(\.\/files\/([^)]+)\)/g, `url('../../node_modules/${scope}/${pkg}/files/$1')`)
      .trim().split('\n').map(line => `  ${line.trim()}`).join('\n');
    out += `\n/* ${family}${css.includes('italic') ? ' italic' : ''}${/\d{3}/.test(css) ? ` ${css.match(/\d{3}/)[0]}` : ''} · ${subset} */\n@font-face {\n${rules}\n}\n`;
  }
}

for (const { file, style, weight } of DIGITS) {
  out += `\n/* CM Digits · ${file} */\n@font-face {\n  font-family: 'CM Digits';\n  font-style: ${style};\n  font-display: swap;\n  font-weight: ${weight};\n  src: url('../../node_modules/katex/dist/fonts/${file}.woff2') format('woff2');\n  unicode-range: U+0030-0039;\n  size-adjust: 104%;\n}\n`;
}

writeFileSync('src/styles/fonts.css', out);
console.log(`src/styles/fonts.css: ${(out.match(/@font-face/g) ?? []).length} faces`);

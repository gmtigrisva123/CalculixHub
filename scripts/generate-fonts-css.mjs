/**
 * Writes src/styles/fonts.css from the installed @fontsource-variable packages.
 *
 * The fonts are served from this origin instead of Google's, so a first visit
 * makes no third-party connection before it can draw text. Each family keeps
 * its usual name ("Geist", not Fontsource's "Geist Variable"), which is the
 * name every stylesheet in the app already asks for.
 *
 * Only the Latin, Latin Extended and Vietnamese subsets are kept. Each is its
 * own file behind a `unicode-range`, so a page of plain English downloads the
 * Latin file alone.
 *
 * Run after changing a font package:  node scripts/generate-fonts-css.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const KEEP = ['latin', 'latin-ext', 'vietnamese'];
const SOURCES = [
  { pkg: 'geist', css: 'index.css', family: 'Geist' },
  { pkg: 'geist-mono', css: 'index.css', family: 'Geist Mono' },
  { pkg: 'newsreader', css: 'opsz.css', family: 'Newsreader' },
  { pkg: 'newsreader', css: 'opsz-italic.css', family: 'Newsreader' },
  { pkg: 'caveat', css: 'index.css', family: 'Caveat' },
];

let out = `/*
 * Self-hosted webfonts. GENERATED by scripts/generate-fonts-css.mjs: edit that
 * script, not this file.
 *
 * The two faces the landing hero is set in are also preloaded from index.html,
 * so they are usually in hand before the first frame is drawn.
 */\n`;

for (const { pkg, css, family } of SOURCES) {
  const source = readFileSync(`node_modules/@fontsource-variable/${pkg}/${css}`, 'utf8');
  // Each block is headed by its file name, e.g. "geist-latin-ext-wght-normal".
  for (const match of source.matchAll(/\/\* ([a-z0-9-]+) \*\/\s*@font-face\s*\{([^}]*)\}/g)) {
    const [, file, body] = match;
    const subset = KEEP.find(name => file.startsWith(`${pkg}-${name}-`) && !(name === 'latin' && file.startsWith(`${pkg}-latin-ext-`)));
    if (!subset) continue;
    const rules = body
      .replace(/font-family:[^;]+;/, `font-family: '${family}';`)
      .replace(/url\(\.\/files\/([^)]+)\)/g, `url('../../node_modules/@fontsource-variable/${pkg}/files/$1')`)
      .trim().split('\n').map(line => `  ${line.trim()}`).join('\n');
    out += `\n/* ${family}${css.includes('italic') ? ' italic' : ''} · ${subset} */\n@font-face {\n${rules}\n}\n`;
  }
}

writeFileSync('src/styles/fonts.css', out);
console.log(`src/styles/fonts.css: ${(out.match(/@font-face/g) ?? []).length} faces`);
